"""Two ablations that explain the main result.

**1. Which features let the model move to a new system?**

The headline model scores 0.956 PR-AUC on held-out cases but drops sharply when
it is tested on an application it has never seen, and its most important
features are *absolute* CPU and memory levels. Those two facts are related: an
absolute level is specific to one deployment, so a model leaning on it cannot
transfer. This ablation splits the features into

* ``absolute``  -- raw levels (mean latency, CPU, memory, request rate)
* ``relative``  -- scale-free quantities only: ratios and z-scores against the
  API's own baseline, coefficients of variation, and error rates

and re-runs the leave-one-system-out evaluation for each, to see which family
actually carries transferable signal.

**2. Does each term of the reliability score earn its weight?**

The score mixes three components. This re-scores every window with one
component removed at a time and measures how well the resulting score still
separates failing windows from healthy ones, so the 0.40 / 0.35 / 0.25 split
can be defended with a number rather than asserted.
"""
from __future__ import annotations

import argparse
import json

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

from .config import (DATA_PROCESSED, MODELS, REPORTS, SYSTEM_NAMES,
                     W_CONSISTENCY, W_ERROR_FREQ, W_FAILURE_RISK)
from .features import FEATURE_COLUMNS
from .train import make_model, scores

# scale-free: a ratio, a z-score, a coefficient of variation or a rate
RELATIVE_FEATURES = [
    "lat50_cv", "consistency", "tail_ratio", "lat_spread", "wl_cv",
    "err_mean", "err_max", "err_delta",
    "lat50_ratio", "lat50_z", "lat90_ratio", "lat90_z", "cv_ratio",
    "wl_ratio", "wl_z", "cpu_ratio", "cpu_z", "mem_ratio", "mem_z",
    "sock_ratio", "disk_ratio",
]
ABSOLUTE_FEATURES = [c for c in FEATURE_COLUMNS if c not in RELATIVE_FEATURES]
FEATURE_SETS = {
    "all": FEATURE_COLUMNS,
    "relative only": RELATIVE_FEATURES,
    "absolute only": ABSOLUTE_FEATURES,
}


def transfer_study(df: pd.DataFrame, n_estimators: int, threshold: float) -> dict:
    out: dict[str, dict] = {}
    y = df.label.values
    for name, cols in FEATURE_SETS.items():
        out[name] = {}
        X = df[cols]
        for sysid in sorted(df.system.unique()):
            mask = (df.system != sysid).values
            if mask.all() or not mask.any():
                continue
            m = make_model(n_estimators).fit(X[mask], y[mask])
            prob = m.predict_proba(X[~mask])[:, 1]
            out[name][sysid] = scores(y[~mask], prob, threshold)
            print("  {:<14} unseen {}: pr_auc={:.3f} recall={:.3f}".format(
                name, sysid, out[name][sysid]["pr_auc"],
                out[name][sysid]["recall"]), flush=True)
        vals = [v["pr_auc"] for v in out[name].values()]
        out[name]["mean_pr_auc"] = float(np.mean(vals)) if vals else None
        print("  {:<14} mean across unseen systems: {:.3f}".format(
            name, out[name]["mean_pr_auc"]))
    return out


def component_study(scored: pd.DataFrame) -> dict:
    """How well does each score variant separate failing from healthy windows?"""
    d = scored.dropna(subset=["reliability_score"]).copy()
    err = d.error_frequency.fillna(0.0)
    risk_t = 1.0 - d.failure_risk
    err_t = 1.0 - err
    cons_t = d.response_consistency

    variants = {
        "full score (0.40 / 0.35 / 0.25)":
            W_FAILURE_RISK * risk_t + W_ERROR_FREQ * err_t + W_CONSISTENCY * cons_t,
        "without failure risk":
            (W_ERROR_FREQ * err_t + W_CONSISTENCY * cons_t)
            / (W_ERROR_FREQ + W_CONSISTENCY),
        "without error frequency":
            (W_FAILURE_RISK * risk_t + W_CONSISTENCY * cons_t)
            / (W_FAILURE_RISK + W_CONSISTENCY),
        "without response consistency":
            (W_FAILURE_RISK * risk_t + W_ERROR_FREQ * err_t)
            / (W_FAILURE_RISK + W_ERROR_FREQ),
        "failure risk alone": risk_t,
        "error frequency alone": err_t,
        "response consistency alone": cons_t,
        "equal weights (1/3 each)": (risk_t + err_t + cons_t) / 3.0,
    }
    y = d.label.values
    out = {}
    for name, series in variants.items():
        # a low score should mean "failing", so rank on the negated score
        s = -series.to_numpy()
        out[name] = {
            "pr_auc": float(average_precision_score(y, s)),
            "roc_auc": float(roc_auc_score(y, s)),
        }
        print("  {:<32} pr_auc={:.3f} roc_auc={:.3f}".format(
            name, out[name]["pr_auc"], out[name]["roc_auc"]), flush=True)
    return out


def write_markdown(transfer: dict, components: dict, n_estimators: int):
    lines = ["# Ablations", "",
             "Generated by `python -m src.ablation`.", "",
             "## 1. Which features transfer to an unseen system?", "",
             "Each model is trained on two applications and tested on the third, "
             "which it has never seen. Forests of {} trees.".format(n_estimators),
             "",
             "| Feature set | " + " | ".join(
                 SYSTEM_NAMES.get(s, s) for s in ("ob", "ss", "tt"))
             + " | Mean |",
             "|---|---|---|---|---|"]
    for name, res in transfer.items():
        row = [name]
        for s in ("ob", "ss", "tt"):
            row.append("{:.3f}".format(res[s]["pr_auc"]) if s in res else "-")
        row.append("**{:.3f}**".format(res["mean_pr_auc"]))
        lines.append("| " + " | ".join(row) + " |")

    rel = transfer.get("relative only", {}).get("mean_pr_auc")
    alll = transfer.get("all", {}).get("mean_pr_auc")
    absl = transfer.get("absolute only", {}).get("mean_pr_auc")
    lines += ["", "Reading: PR-AUC on the held-out application. Higher is better.",
              ""]
    if None not in (rel, alll, absl):
        lines += [
            "**The hypothesis this ablation was built to test was wrong.** "
            "The full model's most important features are absolute CPU and "
            "memory levels, and absolute levels are deployment-specific, so "
            "the expectation was that restricting the model to scale-free "
            "features would transfer better. It transfers markedly worse "
            "({:.3f} against {:.3f} for the full feature set), while the "
            "absolute features alone very nearly match the full set "
            "({:.3f}).".format(rel, alll, absl),
            "",
            "The likely reason is that not every absolute feature is equally "
            "deployment-specific. CPU utilisation is already a normalised "
            "percentage and means much the same thing in any deployment, so it "
            "carries real transferable signal; a ratio against a short "
            "baseline, by contrast, is noisy whenever the baseline itself is "
            "small. Scale-free features are therefore a useful complement "
            "here, not a substitute.",
            "",
            "The practical conclusion for cross-system deployment is that "
            "neither feature family closes the gap on its own: transfer to an "
            "unseen application ({:.3f}) stays well below same-system "
            "performance, so the model should be re-fitted on a new system's "
            "own telemetry rather than dropped in untrained.".format(alll),
            ""]

    lines += ["## 2. Does each term of the score earn its weight?", "",
              "Every window is re-scored with one component removed, then the "
              "score is used to rank windows by how failing they look. A term "
              "that matters shows a clear drop when it is taken out.", "",
              "| Score variant | PR-AUC | ROC-AUC |", "|---|---|---|"]
    for name, r in components.items():
        lines.append("| {} | {:.3f} | {:.3f} |".format(
            name, r["pr_auc"], r["roc_auc"]))
    lines.append("")

    full = components.get("full score (0.40 / 0.35 / 0.25)", {}).get("pr_auc")
    risk = components.get("failure risk alone", {}).get("pr_auc")
    err = components.get("error frequency alone", {}).get("pr_auc")
    cons = components.get("response consistency alone", {}).get("pr_auc")
    if None not in (full, risk, err, cons):
        lines += [
            "**The failure-risk term does nearly all of the work.** On its own "
            "it reaches {:.3f}; removing it collapses the score to {:.3f}. The "
            "other two terms are weak discriminators in isolation ({:.3f} for "
            "error frequency, {:.3f} for response consistency), and the full "
            "weighted score ({:.3f}) actually ranks slightly *worse* than the "
            "calibrated risk alone.".format(
                risk, components["without failure risk"]["pr_auc"], err, cons,
                full),
            "",
            "Two reasons, both visible in the data. Error frequency is only "
            "exported for about a quarter of services, and most faults in this "
            "benchmark are resource faults that degrade latency without "
            "returning errors - so the term is near-constant at zero for most "
            "windows. Response consistency does shift in the right direction "
            "(0.966 healthy against 0.934 failing) but the two distributions "
            "overlap heavily.",
            "",
            "This does not make the composite score pointless, but it does "
            "change what it is for. Its value is **explanation**, not ranking "
            "power: an operator seeing a score of 0.37 can read off which term "
            "caused it, which a bare probability does not give them. If the "
            "only goal were to rank APIs by how likely they are to be failing, "
            "the calibrated risk on its own would be the better choice, and "
            "the proposal's 0.40 / 0.35 / 0.25 weighting should be understood "
            "as a presentation decision rather than an accuracy optimisation.",
            ""]

    path = REPORTS / "ABLATIONS.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print("\nwritten ->", path)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--n-estimators", type=int, default=200,
                   help="smaller than the headline model to keep this tractable")
    p.add_argument("--skip-transfer", action="store_true")
    args = p.parse_args(argv)

    report = json.loads((MODELS / "metrics.json").read_text())
    threshold = report["holdout"]["threshold"]

    scored = pd.read_parquet(DATA_PROCESSED / "scored.parquet")
    scored = scored[scored.usable & ~scored.is_infra]

    transfer = {}
    if not args.skip_transfer:
        print("1. feature families vs an unseen system")
        df = pd.read_parquet(DATA_PROCESSED / "labelled.parquet")
        df = df[df.usable & ~df.is_infra].reset_index(drop=True)
        transfer = transfer_study(df, args.n_estimators, threshold)

    print("\n2. contribution of each score component")
    components = component_study(scored)

    write_markdown(transfer, components, args.n_estimators)
    (REPORTS / "ablations.json").write_text(
        json.dumps({"transfer": transfer, "components": components}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
